"""Check repair-exercise acceptance and failure records without a model server."""

from contextlib import redirect_stdout
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import repair_demo


class RepairDemoTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)

    def workspace(self):
        workspace = Path(tempfile.mkdtemp(dir=self.root)) / "workspace"
        shutil.copytree(repair_demo.FIXTURE, workspace, ignore=shutil.ignore_patterns("__pycache__"))
        for name in ("report.py", "cli.py"):
            with (workspace / name).open("a") as source:
                source.write("\n# Candidate source edit.\n")
        return workspace

    def check(self, workspace):
        with patch("sys.argv", ["repair_demo.py", "check", str(workspace)]), redirect_stdout(io.StringIO()):
            status = repair_demo.main()
        record = json.loads((workspace.parent / "verification.json").read_text())
        self.assertTrue((workspace.parent / "changes.patch").is_file())
        return status, record

    def test_independent_checks_reject_wrong_results_under_optimization(self):
        correct_report = """import math
def summarize(records):
    records = list(records)
    latencies = sorted(r['latency_ms'] for r in records if r['status'] == 'ok')
    n = len(latencies)
    return {'requests': len(records), 'successful': n, 'failed': len(records)-n,
            'mean_ms': sum(latencies)/n if n else 0,
            'p95_ms': latencies[math.ceil(0.95*n)-1] if n else 0}
"""
        for report, failed_case in (("def summarize(records): return {}\n", "empty"),
                                    (correct_report, "cli_all")):
            with self.subTest(failed_case=failed_case):
                workspace = self.workspace()
                (workspace / "report.py").write_text(report)
                (workspace / "cli.py").write_text("print('{}')\n")
                with patch.dict(os.environ, {"PYTHONOPTIMIZE": "1"}):
                    result = repair_demo.run_tests(workspace, extra=True)
                self.assertNotEqual(result["returncode"], 0)
                self.assertIn(failed_case, result["output"])

    def test_allowed_edits_and_bytecode_do_not_fail_file_policy(self):
        workspace = self.workspace()
        cache = workspace / "__pycache__"
        cache.mkdir(exist_ok=True)
        (cache / "report.cpython-310.pyc").write_bytes(b"generated bytecode")
        (workspace / "cli.pyc").write_bytes(b"generated bytecode")
        with patch.object(repair_demo, "run_tests", return_value={"returncode": 0, "output": "passed"}):
            status, record = self.check(workspace)
        self.assertEqual(status, 0)
        self.assertTrue(record["passed"])
        self.assertIn("Candidate source edit", (workspace.parent / "changes.patch").read_text())

    def test_extra_missing_and_modified_protected_files_fail_file_policy(self):
        changes = (
            ("extra", lambda w: (w / "unexpected.py").write_text("unexpected = True\n")),
            ("missing", lambda w: (w / "README.md").unlink()),
            ("modified", lambda w: (w / "test_report.py").write_text("# Altered tests.\n")),
            ("missing_source", lambda w: (w / "cli.py").unlink()),
        )
        for name, change in changes:
            with self.subTest(change=name):
                workspace = self.workspace()
                change(workspace)
                with patch.object(repair_demo, "run_tests", return_value={"returncode": 0, "output": "passed"}):
                    status, record = self.check(workspace)
                self.assertEqual(status, 1)
                self.assertFalse(record["passed"])
                self.assertFalse(record["tests_and_requirements_unchanged"])

    def test_timeout_retains_partial_output_and_verification_artifacts(self):
        for stage, partial in (("public", b"partial public output\n"),
                               ("independent", "partial independent output\n")):
            with self.subTest(stage=stage):
                workspace = self.workspace()
                timeout = subprocess.TimeoutExpired("check", 30, output=partial, stderr=b"partial stderr\n")
                success = subprocess.CompletedProcess("check", 0, stdout="passed", stderr="")
                results = [timeout, success] if stage == "public" else [success, timeout]
                with patch.object(repair_demo.subprocess, "run", side_effect=results):
                    status, record = self.check(workspace)
                self.assertEqual(status, 1)
                self.assertFalse(record["passed"])
                self.assertNotEqual(record[stage]["returncode"], 0)
                self.assertIn("timed out", record[stage]["output"])
                self.assertIn("partial " + stage + " output", record[stage]["output"])
                self.assertIn("partial stderr", record[stage]["output"])


if __name__ == "__main__":
    unittest.main()
